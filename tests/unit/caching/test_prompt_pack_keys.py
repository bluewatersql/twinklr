"""Prompt-pack content must be part of every LLM stage's cache key.

Model IDs were already keyed; prompt content was not, so once cross-run reuse
works an edited prompt would silently serve plans generated by the previous one.
Each stage's key is computed against a copy of the real prompt packs, so editing
one pack proves both that the affected stage's key changes and that unrelated
stages' keys do not.
"""

